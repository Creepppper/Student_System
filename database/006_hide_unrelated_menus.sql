-- 隐藏与高中理科班成绩管理无关的若依菜单
--
-- 说明：
--   1. 只修改 sys_menu.visible，不删除菜单、不删除表、不删除业务数据。
--   2. visible='0' 显示，visible='1' 隐藏；隐藏后路由和权限仍然保留，
--      需要时可以执行文末的恢复语句。
--   3. 本脚本保留学生信息、考试信息、学生成绩、查卷申请，
--      以及用户管理、角色管理、菜单管理这些权限管理入口。
--   4. 代码生成（menu_id=116）默认保留，方便实验三演示；
--      如果最终演示不需要，可再执行文末的可选语句。
-- ============================================================

SET NAMES utf8mb4;

-- 系统监控（2 及其子菜单）、若依官网（4）
-- 系统管理下的部门/岗位/字典/参数/通知/日志（103-108）
-- 日志管理的操作日志/登录日志（500、501）
-- 系统工具下的表单构建/系统接口（115、117）
UPDATE sys_menu
SET visible = '1'
WHERE menu_id IN (
  2, 4,
  103, 104, 105, 106, 107, 108,
  109, 110, 111, 112, 113, 114,
  115, 117,
  500, 501
);

