from collections import OrderedDict

def col(name, typ, null=True, default=None, extra="", comment="", generated=None, pk=False):
    return dict(name=name, type=typ, null=null, default=default, extra=extra,
                comment=comment, generated=generated, pk=pk)

def audit(last=True):
    c = [
        col("created_at", "DATETIME", False, "CURRENT_TIMESTAMP", comment="创建时间"),
        col("created_by", "BIGINT", True, comment="创建人 sys_user.user_id"),
    ]
    if last:
        c += [
            col("updated_at", "DATETIME", False, "CURRENT_TIMESTAMP", extra="ON UPDATE CURRENT_TIMESTAMP", comment="更新时间"),
            col("updated_by", "BIGINT", True, comment="更新人 sys_user.user_id"),
            col("version", "INT", False, "0", comment="乐观锁版本"),
        ]
    return c

